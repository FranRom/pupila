// Automated PR review: deterministic checks over the list of files a PR changes.
// Free, needs no secrets and no LLM, and works on PRs from forks (it only reads
// the git diff). Run by `.github/workflows/review.yml`; also runnable locally:
//
//   BASE_SHA=origin/main HEAD_SHA=HEAD pnpm run review:checks
//
// Findings are `error` (fails the job: it would leak personal data) or `warning`
// (advisory: shown as annotations and in the job summary, never fails the build).
// The rules mirror CONTRIBUTING.md so a reviewer does not have to re-check them.

import { execFileSync } from 'node:child_process';
import { appendFileSync } from 'node:fs';

export interface ChangedFile {
  path: string;
  /** git status letter: A(dded) M(odified) D(eleted) R(enamed) */
  status: string;
  added: number;
  deleted: number;
  /** package.json only: did a dependency field change? Unknown (undefined) counts as yes. */
  depsChanged?: boolean;
}

export interface Finding {
  level: 'error' | 'warning';
  rule: string;
  message: string;
  /** Files the finding is about (capped when printed). */
  files: string[];
}

// Gitignored personal data: committing any of these leaks a user's CV, brief,
// application history or scoring profile into a public repo.
const PERSONAL_FILE_RE =
  /^(config\/(applied\.json|candidate-brief\.md|profile\.json|preferences\.json|slugs\.local\.json|cv\.[a-z0-9]+)|data\/(applications\/(?!\.gitkeep)|swipe-skips\.json|favorites\.json|apply-queue\.json|ai-reviews\.json|jobs-bodies\.json|raw\/(?!\.gitkeep)))/;

// Output the pipeline regenerates (`pnpm run dev`); CONTRIBUTING says not to hand-edit.
const GENERATED_FILES = new Set(['JOBS.md', 'data/jobs.json', 'data/feed.xml']);

const isTestFile = (p: string): boolean =>
  /^tests\//.test(p) || /\.test\.[cm]?[jt]sx?$/.test(p) || /(^|\/)__tests__\//.test(p);

const isSourceFile = (p: string): boolean =>
  /^(src|ui\/src|ui\/plugins|scripts)\/.+\.(ts|tsx|mjs|js)$/.test(p) && !isTestFile(p);

/** Pure: turns the changed-file list into review findings. */
export function reviewChanges(files: ChangedFile[], maxLines = 1500): Finding[] {
  const findings: Finding[] = [];
  const live = files.filter((f) => f.status !== 'D');
  const paths = live.map((f) => f.path);

  const personal = paths.filter((p) => PERSONAL_FILE_RE.test(p));
  if (personal.length > 0) {
    findings.push({
      level: 'error',
      rule: 'personal-data',
      message:
        'These files hold personal data (CV, brief, application history, scoring profile) and must never be committed. Remove them from the PR.',
      files: personal,
    });
  }

  const generated = paths.filter((p) => GENERATED_FILES.has(p));
  if (generated.length > 0) {
    findings.push({
      level: 'warning',
      rule: 'generated-output',
      message:
        'Generated by `pnpm run dev`; CONTRIBUTING asks not to commit or hand-edit them in a code PR unless the change is intentional.',
      files: generated,
    });
  }

  const sourceChanged = live.filter((f) => isSourceFile(f.path) && f.added + f.deleted > 0);
  const testsChanged = paths.some(isTestFile);
  if (sourceChanged.length > 0 && !testsChanged) {
    findings.push({
      level: 'warning',
      rule: 'tests-with-code',
      message:
        'Source changed but no test file did. CONTRIBUTING: when a filter, parser or behaviour changes, update the matching tests in the same change.',
      files: sourceChanged.map((f) => f.path),
    });
  }

  const mcpChanged = paths.filter((p) => /^src\/mcp\/(tools|schemas)\//.test(p));
  if (mcpChanged.length > 0 && !paths.includes('README.md')) {
    findings.push({
      level: 'warning',
      rule: 'mcp-readme',
      message:
        'MCP tool code changed but README.md did not. The README tool-reference table is hand-maintained and must be updated with every tool change.',
      files: mcpChanged,
    });
  }

  const manifest = live.find((f) => f.path === 'package.json');
  if (manifest && manifest.depsChanged !== false && !paths.includes('pnpm-lock.yaml')) {
    findings.push({
      level: 'warning',
      rule: 'lockfile',
      message:
        'Dependencies in package.json changed without pnpm-lock.yaml. Commit the lockfile (CI installs with --frozen-lockfile).',
      files: ['package.json'],
    });
  }

  const workflows = paths.filter((p) => p.startsWith('.github/workflows/'));
  if (workflows.length > 0) {
    findings.push({
      level: 'warning',
      rule: 'workflows',
      message:
        'Workflow files changed. A maintainer should read them closely: third-party actions must be pinned by 40-char commit SHA, and fork PRs must not get write tokens or secrets.',
      files: workflows,
    });
  }

  // Lockfiles and generated output are noise for "is this PR too big to review".
  const totalLines = live
    .filter((f) => f.path !== 'pnpm-lock.yaml' && !GENERATED_FILES.has(f.path))
    .reduce((n, f) => n + f.added + f.deleted, 0);
  if (totalLines > maxLines) {
    findings.push({
      level: 'warning',
      rule: 'size',
      message: `${totalLines} lines changed (> ${maxLines}). CONTRIBUTING asks for small, focused PRs; consider splitting this one.`,
      files: [],
    });
  }

  return findings;
}

const DEPENDENCY_FIELDS = [
  'dependencies',
  'devDependencies',
  'optionalDependencies',
  'peerDependencies',
  'pnpm',
  'overrides',
  'packageManager',
] as const;

/** True when any dependency-related field differs between two package.json texts. */
export function dependencyFieldsChanged(before: string, after: string): boolean {
  try {
    const a = JSON.parse(before) as Record<string, unknown>;
    const b = JSON.parse(after) as Record<string, unknown>;
    return DEPENDENCY_FIELDS.some((k) => JSON.stringify(a[k] ?? null) !== JSON.stringify(b[k] ?? null));
  } catch {
    return true; // unreadable: be conservative and ask for the lockfile
  }
}

export function parseNumstat(output: string, nameStatus: string): ChangedFile[] {
  const statusByPath = new Map<string, string>();
  for (const line of nameStatus.split('\n')) {
    const parts = line.split('\t');
    const status = parts[0]?.[0];
    const path = parts[parts.length - 1];
    if (status && path) statusByPath.set(path, status);
  }
  const files: ChangedFile[] = [];
  for (const line of output.split('\n')) {
    const [a, d, ...rest] = line.split('\t');
    const raw = rest.join('\t');
    if (!raw) continue;
    // The diff is always taken with --no-renames, so `raw` is a plain path.
    const path = raw;
    files.push({
      path,
      status: statusByPath.get(path) ?? 'M',
      added: a === '-' ? 0 : Number(a) || 0,
      deleted: d === '-' ? 0 : Number(d) || 0,
    });
  }
  return files;
}

const esc = (s: string): string => s.replace(/%/g, '%25').replace(/\r/g, '%0D').replace(/\n/g, '%0A');

export function formatSummary(findings: Finding[], fileCount: number): string {
  const lines = ['## Automated review', ''];
  if (findings.length === 0) {
    lines.push(`No findings across ${fileCount} changed file(s).`);
    return lines.join('\n');
  }
  for (const f of findings) {
    lines.push(`- **${f.level === 'error' ? 'Error' : 'Warning'}: \`${f.rule}\`**: ${f.message}`);
    for (const p of f.files.slice(0, 10)) lines.push(`  - \`${p}\``);
    if (f.files.length > 10) lines.push(`  - …and ${f.files.length - 10} more`);
  }
  return lines.join('\n');
}

function git(args: string[]): string {
  return execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

function main(): void {
  const base = process.env.BASE_SHA;
  const head = process.env.HEAD_SHA ?? 'HEAD';
  if (!base) {
    console.error('BASE_SHA is required (e.g. BASE_SHA=origin/main).');
    process.exit(2);
  }
  const range = `${base}...${head}`;
  const files = parseNumstat(
    git(['diff', '--numstat', '--no-renames', range]),
    git(['diff', '--name-status', '--no-renames', range]),
  );
  const manifest = files.find((f) => f.path === 'package.json');
  if (manifest && manifest.status === 'M') {
    // Compare against the merge-base, like the three-dot diff that produced the
    // file list: if `main` moved after the PR branched, its tip is not "before".
    const mergeBase = git(['merge-base', base, head]).trim();
    manifest.depsChanged = dependencyFieldsChanged(
      git(['show', `${mergeBase}:package.json`]),
      git(['show', `${head}:package.json`]),
    );
  }
  const findings = reviewChanges(files);

  for (const f of findings) {
    const where = f.files.length > 0 ? ` (${f.files.slice(0, 5).join(', ')})` : '';
    console.log(`::${f.level} title=${f.rule}::${esc(f.message + where)}`);
  }
  const summary = formatSummary(findings, files.length);
  console.log(summary);
  if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, `${summary}\n`);

  if (findings.some((f) => f.level === 'error')) process.exit(1);
}

// Run only when executed directly, not when imported by tests.
if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) main();
